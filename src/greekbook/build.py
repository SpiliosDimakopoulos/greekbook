"""Turn a project (book.yaml + Markdown) into a Typst document and a PDF."""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from .config import CITATION_STYLES, BookConfig
from .markdown import Code, Diagnostic, markdown_to_typst, relative_base, string, value

PACKAGE_DIR = Path(__file__).parent / "typst" / "packages"
FONTS_DIR = Path(__file__).parent / "fonts"
LIB_IMPORT = '#import "@local/greekbook:0.2.0": *'


class BuildError(Exception):
    """Typst could not compile the document."""


@dataclass
class BuildResult:
    output: Path | None
    typst_source: str
    diagnostics: list[Diagnostic] = field(default_factory=list)
    seconds: float = 0.0


def _root_path(path: Path, root: Path) -> str:
    rel = path.resolve().relative_to(root.resolve())
    return "/" + rel.as_posix()


def _convert_file(
    path: Path, cfg: BookConfig, diagnostics: list[Diagnostic], unnumbered: bool = False
) -> str:
    text = path.read_text(encoding="utf-8")
    try:
        source = path.relative_to(cfg.base_dir).as_posix()
    except ValueError:
        source = path.name
    markup, diags = markdown_to_typst(
        text,
        lang=cfg.language,
        math=cfg.math,
        source=source,
        base=relative_base(path, cfg.base_dir),
        unnumbered=unnumbered,
    )
    diagnostics.extend(diags)
    return f"// ---- {source} ----\n{markup}"


def generate_typst(cfg: BookConfig) -> tuple[str, list[Diagnostic]]:
    """Build the complete Typst source for a project."""
    diagnostics: list[Diagnostic] = []
    root = cfg.base_dir
    width, height = cfg.page_dimensions

    thesis = None
    logo: Code | None = None
    if cfg.template == "thesis":
        t = cfg.thesis
        thesis = {
            "type": t.type, "institution": t.institution, "school": t.school,
            "department": t.department, "program": t.program, "student_id": t.student_id,
            "supervisor": t.supervisor, "committee": t.committee, "place": t.place,
            "date": t.date, "declaration": t.declaration,
        }  # fmt: skip
        if t.logo:
            logo_path = (root / t.logo).resolve()
            if not logo_path.is_file():
                diagnostics.append(Diagnostic("book.yaml", 0, f"δεν βρέθηκε το λογότυπο {t.logo}"))
            else:
                logo = Code(f"image({string(_root_path(logo_path, root))}, height: 100%)")

    front = cfg.front_matter_files()
    has_front = cfg.template == "thesis" or bool(front) or cfg.show_toc
    args: dict[str, object] = {
        "template": cfg.template,
        "title": cfg.title,
        "subtitle": cfg.subtitle,
        "author": cfg.author,
        "lang": cfg.language,
        "page-size": (width, height),
        "chapter-numbering": cfg.chapter_numbering,
        "front-matter": has_front,
        "dedication": cfg.dedication,
        "epigraph": cfg.epigraph,
        "copyright": cfg.copyright,
        "publisher": cfg.publisher,
        "year": cfg.year,
        "keywords": cfg.keywords,
        "thesis": thesis,
        "logo": logo,
    }
    if cfg.font:
        args["font"] = cfg.font
    if cfg.font_size:
        args["font-size"] = Code(cfg.font_size)
    if cfg.paper_color:
        args["paper"] = cfg.paper_color

    parts = [
        "// Generated by greekbook — edit the Markdown sources, not this file.",
        LIB_IMPORT,
        "#show: book.with(" + ", ".join(f"{k}: {value(v)}" for k, v in args.items()) + ")",
    ]
    for path in front:
        parts.append(_convert_file(path, cfg, diagnostics, unnumbered=True))
    if cfg.show_toc or cfg.list_of_figures or cfg.list_of_tables:
        parts.append(
            f"#gb-outlines(toc: {value(cfg.show_toc)}, figures: {value(cfg.list_of_figures)}, "
            f"tables: {value(cfg.list_of_tables)})"
        )
    if has_front:
        parts.append("#show: mainmatter")
    for path in cfg.chapter_files():
        parts.append(_convert_file(path, cfg, diagnostics))

    bib = cfg.bibliography_files()
    if bib:
        style = CITATION_STYLES.get(cfg.citation_style, cfg.citation_style)
        if style.endswith(".csl"):
            style = _root_path(root / style, root)
        paths = value(tuple(_root_path(p, root) for p in bib))
        parts.append(f"#bibliography({paths}, style: {string(style)})")

    appendices = cfg.appendix_files()
    if appendices:
        parts.append("#show: appendices")
        for path in appendices:
            parts.append(_convert_file(path, cfg, diagnostics))
    return "\n\n".join(parts) + "\n", diagnostics


def compile_typst(
    source: str,
    root: Path,
    fmt: Literal["pdf", "svg", "png", "html"] = "pdf",
    pdf_standard: Any = "1.7",
    ppi: float | None = None,
) -> bytes | list[bytes]:
    import typst

    compiler = typst.Compiler(
        root=str(root),
        font_paths=[str(FONTS_DIR)],
        package_path=str(PACKAGE_DIR),
    )
    standards = [pdf_standard] if fmt == "pdf" and pdf_standard != "1.7" else []
    try:
        result: bytes | list[bytes] | None = compiler.compile(
            source.encode("utf-8"), format=fmt, ppi=ppi, pdf_standards=standards
        )
    except typst.TypstError as exc:  # pragma: no cover - message formatting only
        hints = "".join(f"\n  hint: {h}" for h in getattr(exc, "hints", []) or [])
        raise BuildError(f"{exc.message}{hints}") from exc
    if result is None:  # pragma: no cover - only when an output path is given
        raise BuildError("Typst did not return a document")
    return result


def build(cfg: BookConfig, output: Path | None = None, keep_typst: bool = False) -> BuildResult:
    """Build the PDF for ``cfg`` and return what happened."""
    started = time.perf_counter()
    source, diagnostics = generate_typst(cfg)
    out = output or cfg.output_path
    pdf = compile_typst(source, cfg.base_dir, pdf_standard=cfg.pdf_standard)
    assert isinstance(pdf, bytes)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(pdf)
    if keep_typst:
        out.with_suffix(".typ").write_text(source, encoding="utf-8")
    return BuildResult(out, source, diagnostics, time.perf_counter() - started)
